ALTER TABLE public.inventory_items
  ADD COLUMN IF NOT EXISTS target_stock numeric(12,3) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS preferred_supplier text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS storage_location text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS count_frequency_days integer NOT NULL DEFAULT 7,
  ADD COLUMN IF NOT EXISTS tracks_expiry boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS last_counted_at timestamptz;

UPDATE public.inventory_items
SET target_stock = GREATEST(target_stock, minimum_stock, current_stock, 0)
WHERE target_stock < minimum_stock OR target_stock = 0;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'inventory_items_target_stock_check'
      AND conrelid = 'public.inventory_items'::regclass
  ) THEN
    ALTER TABLE public.inventory_items
      ADD CONSTRAINT inventory_items_target_stock_check
      CHECK (target_stock >= minimum_stock);
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'inventory_items_count_frequency_check'
      AND conrelid = 'public.inventory_items'::regclass
  ) THEN
    ALTER TABLE public.inventory_items
      ADD CONSTRAINT inventory_items_count_frequency_check
      CHECK (count_frequency_days BETWEEN 1 AND 365);
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.inventory_counts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  scope text NOT NULL DEFAULT 'full'
    CHECK (scope = ANY (ARRAY['full', 'critical'])),
  status text NOT NULL DEFAULT 'draft'
    CHECK (status = ANY (ARRAY['draft', 'submitted', 'reconciled', 'cancelled'])),
  notes text NOT NULL DEFAULT '',
  requires_review boolean NOT NULL DEFAULT false,
  started_by uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  completed_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  reviewed_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  started_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  reviewed_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.inventory_count_lines (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  count_id uuid NOT NULL REFERENCES public.inventory_counts(id) ON DELETE CASCADE,
  inventory_item_id uuid NOT NULL REFERENCES public.inventory_items(id) ON DELETE RESTRICT,
  expected_stock numeric(12,3) NOT NULL,
  counted_stock numeric(12,3) CHECK (counted_stock >= 0),
